//! A tiny translation layer. Keys are the English UI strings themselves, so
//! a missing translation simply shows English instead of a placeholder.

use std::{
    collections::HashMap,
    sync::{
        OnceLock,
        atomic::{AtomicU8, Ordering},
    },
};

use serde::{Deserialize, Serialize};

#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize,
)]
pub enum Lang {
    #[default]
    En,
    Cs,
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::En, Lang::Cs];
}

impl std::fmt::Display for Lang {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Lang::En => "English",
            Lang::Cs => "Čeština",
        })
    }
}

static LANG: AtomicU8 = AtomicU8::new(0);

pub fn set_lang(lang: Lang) {
    LANG.store(lang as u8, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    match LANG.load(Ordering::Relaxed) {
        1 => Lang::Cs,
        _ => Lang::En,
    }
}

fn czech() -> &'static HashMap<&'static str, &'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| CS.iter().copied().collect())
}

/// Translates a UI string into the active language
pub fn t(s: &'static str) -> &'static str {
    match lang() {
        Lang::En => s,
        Lang::Cs => czech().get(s).copied().unwrap_or(s),
    }
}

